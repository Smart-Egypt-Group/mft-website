#!/usr/bin/env node
// Regenerates src/content/platform-facts.js from a seg-audit checkout, so the numbers
// the site publishes about the platform come from the code and never drift.
//
//   node scripts/platform-facts.js /path/to/seg-audit
//
// Sources (all inside the seg-audit repo, nothing guessed):
//   checks    unique check codes in docs/report-check-coverage.md, the file
//             tools/gen_check_registry.py generates from the engines (CI checks it)
//   reports   report keys in audit-engine/app/reports/catalog.py (REPORTS)
//   axes      axis keys in the same catalog (AXES)
//   sections  section keys in the same catalog (SECTIONS)
//   tests     test functions in audit-engine/tests and pdf-service/tests (def test_)
//             plus it()/test() calls in the portal's test files. A static count:
//             parametrized cases make the collected number higher, never lower.
//   testRatio test lines ÷ application lines (.py/.ts/.tsx), same file sets.
// Published figures are floored (tests to the hundred) so "more than N" stays true.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const repo = process.argv[2];
if (!repo || !fs.existsSync(path.join(repo, 'audit-engine'))) {
  console.error('usage: node scripts/platform-facts.js /path/to/seg-audit');
  process.exit(2);
}
const read = (p) => fs.readFileSync(path.join(repo, p), 'utf8');
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' }).trim();
const files = (...dirs) => git('ls-files', '--', ...dirs).split('\n').filter(Boolean);
const lines = (list) => list.reduce((n, f) => n + read(f).split('\n').length, 0);

// --- checks: the generated registry document
const coverage = read('docs/report-check-coverage.md');
const checks = new Set([...coverage.matchAll(/^- `([A-Z0-9_]+)`/gm)].map((m) => m[1])).size;

// --- reports / axes / sections: catalog.py builds each dict from constructor calls
// (`REPORTS: dict[str, Report] = { r.key: r for r in ( Report("…", …), … ) }`).
// Count the calls inside that block only; the same constructor also appears elsewhere
// (superseded reports), which must not be counted.
const catalog = read('audit-engine/app/reports/catalog.py');
function blockCount(name, ctor) {
  const start = catalog.search(new RegExp(`^${name}\\b[^=\\n]*=\\s*\\{`, 'm'));
  if (start < 0) return null;
  const end = catalog.slice(start).search(/^\}/m);
  if (end < 0) return null;
  const block = catalog.slice(start, start + end);
  return (block.match(new RegExp(`^\\s+${ctor}\\("`, 'gm')) || []).length || null;
}
const reports = blockCount('REPORTS', 'Report');
const axes = blockCount('AXES', 'Axis');
const sections = blockCount('SECTIONS', 'Section');

// --- tests and the test-to-code ratio
const pyTests = files('audit-engine/tests', 'pdf-service/tests').filter((f) => f.endsWith('.py'));
const tsTests = files('portal').filter((f) => /\.(test|spec)\.(ts|tsx)$/.test(f));
const testFns =
  pyTests.reduce((n, f) => n + (read(f).match(/^\s*(async\s+)?def test_/gm) || []).length, 0) +
  tsTests.reduce((n, f) => n + (read(f).match(/\b(it|test)\(/g) || []).length, 0);
const appFiles = files('audit-engine/app', 'pdf-service/app', 'portal/src')
  .filter((f) => /\.(py|ts|tsx)$/.test(f) && !/\.(test|spec)\.(ts|tsx)$/.test(f));
const testFiles = [...pyTests, ...tsTests];
const testRatio = Math.round((lines(testFiles) / lines(appFiles)) * 100) / 100;

const facts = {
  checks,
  reports,
  axes,
  sections,
  testsFloor: Math.floor(testFns / 100) * 100,
  testRatio,
  sourceCommit: git('rev-parse', '--short', 'HEAD'),
  measuredOn: new Date().toISOString().slice(0, 10)
};
for (const [k, v] of Object.entries(facts)) {
  if (v === null || v === 0 || Number.isNaN(v)) {
    console.error(`could not measure "${k}"; the seg-audit layout may have changed`);
    process.exit(1);
  }
}

const out = path.join(__dirname, '..', 'src', 'content', 'platform-facts.js');
fs.writeFileSync(
  out,
  `// Generated by scripts/platform-facts.js from seg-audit@${facts.sourceCommit} on ${facts.measuredOn}.\n` +
    '// Do not edit by hand: rerun the script against a seg-audit checkout.\n' +
    `module.exports = ${JSON.stringify(facts, null, 2)};\n`
);
console.log(`wrote ${path.relative(process.cwd(), out)}`, facts);
